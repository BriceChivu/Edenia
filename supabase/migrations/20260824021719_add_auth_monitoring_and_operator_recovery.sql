create or replace function private.record_auth_health_check(
  p_outcome text,
  p_http_status integer,
  p_latency_ms integer
)
returns table (
  outcome text,
  alert_state text,
  alert_action text,
  consecutive_provider_failures integer,
  checked_at timestamptz
)
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  previous_status private.auth_health_status%rowtype;
  failure_count integer;
  next_alert_state text;
  next_alert_action text := 'none';
  check_time timestamptz := pg_catalog.now();
begin
  if p_outcome not in (
    'available',
    'expected_client_error',
    'provider_unavailable',
    'network_error'
  ) then
    raise exception 'Auth health outcome is invalid' using errcode = '22023';
  end if;
  if p_latency_ms is null or p_latency_ms not between 0 and 60000 then
    raise exception 'Auth health latency is invalid' using errcode = '22023';
  end if;
  if (
    p_outcome = 'network_error' and p_http_status is not null
  ) or (
    p_outcome = 'available'
    and (p_http_status is null or p_http_status not between 200 and 299)
  ) or (
    p_outcome = 'expected_client_error'
    and (p_http_status is null or p_http_status not between 400 and 499)
  ) or (
    p_outcome = 'provider_unavailable'
    and (p_http_status is null or p_http_status not between 500 and 599)
  ) then
    raise exception 'Auth health status does not match outcome'
      using errcode = '22023';
  end if;

  select value.* into strict previous_status
  from private.auth_health_status as value
  where value.singleton
  for update;

  failure_count := case
    when p_outcome in ('provider_unavailable', 'network_error')
      then previous_status.consecutive_provider_failures + 1
    else 0
  end;
  next_alert_state := case when failure_count >= 3 then 'open' else 'healthy' end;
  if next_alert_state = 'open' and previous_status.alert_state <> 'open' then
    next_alert_action := 'open';
  elsif next_alert_state = 'healthy' and previous_status.alert_state = 'open' then
    next_alert_action := 'close';
  end if;

  insert into private.auth_health_checks (
    checked_at,
    outcome,
    http_status,
    latency_ms
  ) values (
    check_time,
    p_outcome,
    p_http_status,
    p_latency_ms
  );

  delete from private.auth_health_checks as old_check
  where old_check.checked_at < check_time - interval '35 days';

  update private.auth_health_status as value
  set last_checked_at = check_time,
      last_outcome = p_outcome,
      last_http_status = p_http_status,
      last_latency_ms = p_latency_ms,
      consecutive_provider_failures = failure_count,
      alert_state = next_alert_state,
      alert_opened_at = case
        when next_alert_action = 'open' then check_time
        else value.alert_opened_at
      end,
      alert_closed_at = case
        when next_alert_action = 'close' then check_time
        else value.alert_closed_at
      end,
      updated_at = check_time
  where value.singleton;

  return query select
    p_outcome,
    next_alert_state,
    next_alert_action,
    failure_count,
    check_time;
end;
$$;

revoke execute on function private.record_auth_health_check(text, integer, integer)
  from public, anon, authenticated, service_role;
grant execute on function private.record_auth_health_check(text, integer, integer)
