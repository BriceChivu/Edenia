create or replace function private.record_under_13_account_lock(
  p_incident_id uuid,
  p_target_confirmation text,
  p_guardian_consent_verified boolean,
  p_session_status text
)
returns table (
  status text,
  manual_removal_required boolean,
  session_status text
)
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  incident private.learner_profile_operator_recovery_incidents%rowtype;
  lock_id uuid;
begin
  if p_incident_id is null
    or p_guardian_consent_verified is null
    or p_session_status not in ('unknown', 'valid', 'revoked')
  then
    raise exception 'Under-13 incident metadata is invalid' using errcode = '22023';
  end if;
  select value.* into strict incident
  from private.learner_profile_operator_recovery_incidents as value
  where value.incident_id = p_incident_id
  for update;
  if incident.incident_kind <> 'under-13'
    or incident.server_gate_after <> 'off'
  then
    raise exception 'Under-13 lock is not available' using errcode = '42501';
  end if;
  if p_target_confirmation is distinct from 'UNDER-13 ' || incident.target_user_id::text then
    raise exception 'Under-13 target confirmation is invalid'
      using errcode = '22023';
  end if;
  if incident.status in ('completed', 'aborted') then
    raise exception 'Under-13 incident is closed' using errcode = '42501';
  end if;
  if incident.status = 'guardian_consent_recorded'
    and not p_guardian_consent_verified
  then
    raise exception 'Verified guardian consent cannot be reversed'
      using errcode = '22023';
  end if;
  if not exists (
    select 1
    from private.learner_profile_access_control as access_control
    where access_control.singleton
      and access_control.rollout_state = 'off'
  ) then
    raise exception 'Under-13 lock requires the server gate to be off'
      using errcode = '42501';
  end if;
  update private.learner_profile_operator_recovery_incidents as value
  set status = case
        when p_guardian_consent_verified then 'guardian_consent_recorded'
        else 'locked'
      end,
      session_status = p_session_status,
      updated_at = pg_catalog.now()
  where value.incident_id = p_incident_id;

  if p_guardian_consent_verified then
    update private.learner_profile_account_locks as lock_record
    set guardian_consent_verified = true,
        session_status = p_session_status
    where lock_record.incident_id = p_incident_id
      and lock_record.user_id = incident.target_user_id;
    return query select
      'guardian_consent_recorded'::text,
      false,
      p_session_status;
    return;
  end if;

  lock_id := extensions.gen_random_uuid();
  insert into private.learner_profile_account_locks (
    lock_id,
    incident_id,
    user_id,
    guardian_consent_verified,
    session_status
  ) values (
    lock_id,
    p_incident_id,
    incident.target_user_id,
    false,
    p_session_status
  )
  on conflict (incident_id, user_id) do update
  set guardian_consent_verified = excluded.guardian_consent_verified,
      session_status = excluded.session_status,
      locked_at = pg_catalog.now();

  return query select
    'locked'::text,
    true,
    p_session_status;
end;
$$;

