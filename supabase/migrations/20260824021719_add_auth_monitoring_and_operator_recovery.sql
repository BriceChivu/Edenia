  from public, anon, authenticated, service_role;
grant execute on function private.record_under_13_account_lock(uuid, text, boolean, text)
  to service_role;

create or replace function private.record_under_13_profile_removal(
  p_incident_id uuid,
  p_target_confirmation text,
  p_session_status text,
  p_remaining_heads bigint,
  p_remaining_versions bigint
)
returns table (
  status text,
  removal_status text,
  session_status text,
  remaining_heads bigint,
  remaining_versions bigint
)
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  incident private.learner_profile_operator_recovery_incidents%rowtype;
  next_status text;
  recorded_at timestamptz := pg_catalog.now();
begin
  if p_incident_id is null
    or p_session_status not in ('unknown', 'valid', 'revoked')
    or p_remaining_heads is null
    or p_remaining_heads < 0
    or p_remaining_versions is null
    or p_remaining_versions < 0
  then
    raise exception 'Under-13 removal metadata is invalid' using errcode = '22023';
  end if;

  select value.* into strict incident
  from private.learner_profile_operator_recovery_incidents as value
  where value.incident_id = p_incident_id
  for update;
  if incident.incident_kind <> 'under-13'
    or incident.server_gate_after <> 'off'
    or incident.status not in ('locked', 'completed')
  then
    raise exception 'Under-13 removal is not available' using errcode = '42501';
  end if;
  if incident.status = 'completed'
    and (p_remaining_heads <> 0 or p_remaining_versions <> 0)
  then
    raise exception 'Under-13 removal was already completed' using errcode = '22023';
  end if;
  if not exists (
    select 1
    from private.learner_profile_access_control as access_control
    where access_control.singleton
      and access_control.rollout_state = 'off'
  ) then
    raise exception 'Under-13 removal requires the server gate to be off'
      using errcode = '42501';
  end if;
  if p_target_confirmation is distinct from 'UNDER-13 ' || incident.target_user_id::text then
    raise exception 'Under-13 target confirmation is invalid'
      using errcode = '22023';
  end if;

  next_status := case
    when p_remaining_heads = 0 and p_remaining_versions = 0 then 'completed'
    else 'incomplete'
  end;
  update private.learner_profile_operator_recovery_incidents as value
  set status = case when next_status = 'completed' then 'completed' else 'locked' end,
      removal_status = next_status,
      removal_remaining_heads = p_remaining_heads,
      removal_remaining_versions = p_remaining_versions,
      removal_recorded_at = recorded_at,
      session_status = p_session_status,
      updated_at = recorded_at
  where value.incident_id = p_incident_id;

  return query select
    next_status,
    next_status,
    p_session_status,
    p_remaining_heads,
    p_remaining_versions;
end;
$$;

