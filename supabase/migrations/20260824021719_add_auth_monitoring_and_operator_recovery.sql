create or replace function private.restore_learner_profile_from_operator_candidate(
  p_incident_id uuid,
  p_operation_id uuid,
  p_version_id uuid,
  p_candidate_confirmation text
)
returns table (
  status text,
  incident_id uuid,
  target_user_id uuid,
  source_version_id uuid,
  restored_version_id uuid,
  profile_id uuid,
  generation bigint,
  revision bigint,
  payload_sha256 text,
  payload_bytes integer,
  restored_at timestamptz,
  displaced_version_id uuid,
  protected_until timestamptz
)
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  incident private.learner_profile_operator_recovery_incidents%rowtype;
  candidate public.learner_profile_versions%rowtype;
  current_head public.learner_profile_heads%rowtype;
  previous_version public.learner_profile_versions%rowtype;
  new_version_id uuid;
  next_revision bigint;
  restored_at timestamptz := pg_catalog.now();
  protection_deadline timestamptz;
  request_digest text;
begin
  if p_incident_id is null or p_operation_id is null or p_version_id is null then
    raise exception 'Operator restore identity is invalid' using errcode = '22023';
  end if;

  select value.* into strict incident
  from private.learner_profile_operator_recovery_incidents as value
  where value.incident_id = p_incident_id
  for update;
  if incident.incident_kind <> 'profile-recovery'
    or incident.server_gate_after <> 'off'
  then
    raise exception 'Operator profile recovery is not available'
      using errcode = '42501';
  end if;
  if not exists (
    select 1
    from private.learner_profile_access_control as access_control
    where access_control.singleton
      and access_control.rollout_state = 'off'
  ) then
    raise exception 'Operator profile recovery requires the server gate to be off'
      using errcode = '42501';
  end if;
  if p_candidate_confirmation is distinct from 'RESTORE ' || p_version_id::text then
    raise exception 'Recovery candidate confirmation is invalid'
      using errcode = '22023';
  end if;
  if incident.status = 'restored' then
    if incident.restore_operation_id <> p_operation_id then
      raise exception 'Recovery incident was already restored'
        using errcode = '22023';
    end if;
    return query
    select
      'already_restored'::text,
      incident.incident_id,
      incident.target_user_id,
      version.id,
      incident.restored_version_id,
      version.profile_id,
      version.generation,
      version.revision,
      version.payload_sha256,
      version.payload_bytes,
      version.created_at,
      recovery.displaced_version_id,
      recovery.protected_until
    from public.learner_profile_versions as version
    join private.learner_profile_recoveries as recovery
      on recovery.restored_version_id = version.id
     and recovery.user_id = version.user_id
    where version.id = incident.restored_version_id
      and recovery.operation_id = p_operation_id;
    return;
  end if;
  if incident.status <> 'started' then
    raise exception 'Recovery incident is not open' using errcode = '42501';
  end if;

  select version.* into strict candidate
  from public.learner_profile_versions as version
  where version.id = p_version_id
    and version.user_id = incident.target_user_id;
  perform private.assert_learner_profile_envelope(candidate.envelope);
  if candidate.payload_sha256 is distinct from candidate.envelope #>> '{integrity,payloadSha256}'
    or candidate.payload_bytes is distinct from (candidate.envelope #>> '{integrity,byteLength}')::integer
  then
    raise exception 'Operator recovery candidate metadata is invalid'
      using errcode = '22023';
  end if;

  select head.* into current_head
  from public.learner_profile_heads as head
  where head.user_id = incident.target_user_id
  for update;

  select coalesce(max(version.revision), 0) + 1
  into next_revision
  from public.learner_profile_versions as version
  where version.user_id = incident.target_user_id
    and version.profile_id = candidate.profile_id
    and version.generation = candidate.generation;
  if next_revision <= candidate.revision then
    next_revision := candidate.revision + 1;
  end if;

  request_digest := pg_catalog.rtrim(pg_catalog.translate(
    pg_catalog.encode(
      extensions.digest(
        pg_catalog.convert_to(
          private.canonical_jsonb_text(pg_catalog.jsonb_build_object(
            'candidateVersionId', p_version_id,
            'incidentId', p_incident_id,
            'operationId', p_operation_id,
            'ownerId', incident.target_user_id
          )),
          'UTF8'
        ),
        'sha256'
      ),
      'base64'
    ),
    '+/',
    '-_'
  ), '=');
  new_version_id := extensions.gen_random_uuid();
  protection_deadline := restored_at + interval '30 days';

  insert into public.learner_profile_versions (
    id,
    user_id,
    profile_id,
    generation,
    revision,
    base_revision,
    envelope,
    payload_sha256,
    payload_bytes
  ) values (
    new_version_id,
    incident.target_user_id,
    candidate.profile_id,
    candidate.generation,
    next_revision,
    next_revision - 1,
    candidate.envelope,
    candidate.payload_sha256,
    candidate.payload_bytes
  );

  insert into private.learner_profile_recoveries (
    user_id,
    operation_id,
    request_sha256,
    source,
    source_candidate_id,
    source_profile_id,
    source_generation,
    source_revision,
    restored_profile_id,
    restored_generation,
    restored_revision,
    restored_version_id,
    displaced_profile_id,
    displaced_generation,
    displaced_revision,
    displaced_version_id,
    restored_at,
    protected_until
  ) values (
    incident.target_user_id,
    p_operation_id,
    request_digest,
    'operator',
    null,
    candidate.profile_id,
    candidate.generation,
    candidate.revision,
    candidate.profile_id,
    candidate.generation,
    next_revision,
    new_version_id,
    current_head.profile_id,
    current_head.generation,
    current_head.revision,
    current_head.current_version_id,
    restored_at,
    protection_deadline
  );

  if current_head.user_id is null then
    insert into public.learner_profile_heads (
      user_id,
      profile_id,
      generation,
      revision,
      current_version_id,
      created_at,
      updated_at
    ) values (
      incident.target_user_id,
      candidate.profile_id,
      candidate.generation,
      next_revision,
      new_version_id,
      restored_at,
      restored_at
    );
  else
    update public.learner_profile_heads as head
    set profile_id = candidate.profile_id,
        generation = candidate.generation,
        revision = next_revision,
        current_version_id = new_version_id,
        updated_at = restored_at
    where head.user_id = incident.target_user_id
      and head.current_version_id = current_head.current_version_id;
    if not found then
      raise exception 'Learner profile head changed during operator recovery'
        using errcode = '40001';
    end if;
  end if;

  update private.learner_profile_operator_recovery_incidents as value
  set status = 'restored',
      selected_version_id = p_version_id,
      restore_operation_id = p_operation_id,
      restored_version_id = new_version_id,
      updated_at = restored_at
  where value.incident_id = p_incident_id;

  return query select
    'restored'::text,
    p_incident_id,
    incident.target_user_id,
    p_version_id,
    new_version_id,
    candidate.profile_id,
    candidate.generation,
    next_revision,
    candidate.payload_sha256,
    candidate.payload_bytes,
    restored_at,
    current_head.current_version_id,
    protection_deadline;
end;
$$;

