-- Keep Auth availability evidence aggregate and give operators one fenced,
-- auditable path for serious learner-profile incidents.
create table private.auth_health_checks (
  id bigint generated by default as identity primary key,
  checked_at timestamptz not null default pg_catalog.now(),
  outcome text not null,
  http_status integer,
  latency_ms integer not null,
  constraint auth_health_checks_outcome_check check (
    outcome in (
      'available',
      'expected_client_error',
      'provider_unavailable',
      'network_error'
    )
  ),
  constraint auth_health_checks_status_check check (
    (outcome = 'available' and http_status between 200 and 299)
    or (
      outcome = 'expected_client_error'
      and http_status between 400 and 499
    )
    or (
      outcome = 'provider_unavailable'
      and http_status between 500 and 599
    )
    or (outcome = 'network_error' and http_status is null)
  ),
  constraint auth_health_checks_latency_check check (
    latency_ms between 0 and 60000
  )
);

comment on table private.auth_health_checks is
  'Aggregate Auth probe outcomes only. It contains no account, profile, request, or response data.';

create index auth_health_checks_checked_at_idx
  on private.auth_health_checks (checked_at desc, id desc);

