  p_incident_id uuid,
  p_incident_kind text,
  p_target_user_id uuid,
  p_target_confirmation text,
  p_deployed_commit text,
  p_account_features_rollout text,
  p_learner_profile_lifecycle_enabled boolean,
  p_emergency_accountless_rollback_enabled boolean,
  p_legacy_progress_migration_enabled boolean,
  p_accountless_profile_final_cutover_at timestamptz,
  p_session_status text
)
returns table (
  status text,
  incident_id uuid,
  target_user_id uuid,
  server_gate_before text,
  server_gate_after text,
  deployed_commit text,
  started_at timestamptz
)
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  existing_incident private.learner_profile_operator_recovery_incidents%rowtype;
  access_control private.learner_profile_access_control%rowtype;
  started_at timestamptz := pg_catalog.now();
begin
  if p_incident_id is null
    or p_incident_kind not in ('profile-recovery', 'under-13')
    or p_target_user_id is null
    or p_deployed_commit is null
    or p_deployed_commit !~ '^[0-9a-f]{7,64}$'
    or p_account_features_rollout not in ('off', 'internal', 'public')
    or p_learner_profile_lifecycle_enabled is null
    or p_emergency_accountless_rollback_enabled is null
    or p_legacy_progress_migration_enabled is null
    or p_session_status not in ('unknown', 'valid', 'revoked')
  then
    raise exception 'Recovery incident metadata is invalid' using errcode = '22023';
  end if;
  if (
    p_incident_kind = 'profile-recovery'
    and p_target_confirmation is distinct from 'RECOVER ' || p_target_user_id::text
  ) or (
    p_incident_kind = 'under-13'
    and p_target_confirmation is distinct from 'UNDER-13 ' || p_target_user_id::text
  ) then
    raise exception 'Recovery target confirmation is invalid' using errcode = '22023';
  end if;
  perform 1
  from auth.users as account
  where account.id = p_target_user_id;
  if not found then
    raise exception 'Recovery target account does not exist' using errcode = '22023';
  end if;

  select value.* into existing_incident
  from private.learner_profile_operator_recovery_incidents as value
  where value.incident_id = p_incident_id;
  if found then
    if existing_incident.target_user_id is distinct from p_target_user_id
      or existing_incident.incident_kind is distinct from p_incident_kind
      or existing_incident.deployed_commit is distinct from p_deployed_commit
      or existing_incident.account_features_rollout is distinct from p_account_features_rollout
      or existing_incident.learner_profile_lifecycle_enabled is distinct from p_learner_profile_lifecycle_enabled
      or existing_incident.emergency_accountless_rollback_enabled is distinct from p_emergency_accountless_rollback_enabled
      or existing_incident.legacy_progress_migration_enabled is distinct from p_legacy_progress_migration_enabled
      or existing_incident.accountless_profile_final_cutover_at is distinct from p_accountless_profile_final_cutover_at
      or existing_incident.session_status is distinct from p_session_status
    then
      raise exception 'Recovery incident identity was reused'
        using errcode = '22023';
    end if;
    select value.* into strict access_control
    from private.learner_profile_access_control as value
    where value.singleton
    for update;
    if access_control.rollout_state <> 'off' or access_control.developer_user_id is not null then
      update private.learner_profile_access_control as value
      set rollout_state = 'off',
          developer_user_id = null,
          updated_at = started_at
      where value.singleton;
    end if;
    return query select
      'already_started'::text,
      existing_incident.incident_id,
      existing_incident.target_user_id,
      existing_incident.server_gate_before,
      existing_incident.server_gate_after,
      existing_incident.deployed_commit,
      existing_incident.created_at;
    return;
  end if;

  select value.* into strict access_control
  from private.learner_profile_access_control as value
  where value.singleton
  for update;

  update private.learner_profile_access_control as value
  set rollout_state = 'off',
      developer_user_id = null,
      updated_at = started_at
  where value.singleton;

  insert into private.learner_profile_operator_recovery_incidents (
    incident_id,
    incident_kind,
    target_user_id,
    deployed_commit,
    account_features_rollout,
    learner_profile_lifecycle_enabled,
    emergency_accountless_rollback_enabled,
    legacy_progress_migration_enabled,
    accountless_profile_final_cutover_at,
    server_gate_before,
    server_gate_after,
    session_status,
    created_at,
    updated_at
  ) values (
    p_incident_id,
    p_incident_kind,
    p_target_user_id,
    p_deployed_commit,
    p_account_features_rollout,
    p_learner_profile_lifecycle_enabled,
    p_emergency_accountless_rollback_enabled,
    p_legacy_progress_migration_enabled,
    p_accountless_profile_final_cutover_at,
    access_control.rollout_state,
    'off',
    p_session_status,
    started_at,
    started_at
  );

  return query select
    'started'::text,
    p_incident_id,
    p_target_user_id,
    access_control.rollout_state,
    'off'::text,
    p_deployed_commit,
    started_at;
end;
$$;

